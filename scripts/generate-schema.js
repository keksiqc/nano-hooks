import { readFileSync, writeFileSync } from "node:fs";

import { CONFIG_SHAPE } from "../src/lib/config-shape.js";

const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $comment: "Generated by pnpm schema.",
  title: "nano-hooks configuration",
  ...CONFIG_SHAPE,
};

const file = new URL("../schema.json", import.meta.url);
const generated = JSON.stringify(schema);
if (process.argv.includes("--check")) {
  if (JSON.stringify(JSON.parse(readFileSync(file, "utf8"))) !== generated) {
    throw new Error("schema.json is out of date. Run pnpm schema.");
  }
} else {
  writeFileSync(file, `${JSON.stringify(schema, null, 2)}\n`);
}
