import { readFileSync, writeFileSync } from "node:fs";

import { NON_BLANK, STAGED_DEFAULTS, VALID_HOOKS } from "../src/lib/config.js";

const command = { type: "string", pattern: NON_BLANK.source };
const commandList = { $ref: "#/$defs/commandList" };

const stagedOptionDescriptions = {
  allowEmpty: "Allow a commit that becomes empty after running staged tasks.",
  bail: "Stop running staged tasks after the first command fails.",
  parallel: "Run tasks for different staged patterns concurrently.",
  restage: "Stage the changes made by staged tasks.",
};

const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $comment: "Generated by pnpm schema.",
  title: "nano-hooks configuration",
  type: "object",
  additionalProperties: false,
  properties: {
    $schema: { ...command, description: "Schema path or URL for editor validation." },
    options: {
      type: "object",
      additionalProperties: false,
      properties: {
        ...Object.fromEntries(
          Object.keys(STAGED_DEFAULTS).map((name) => [
            name,
            { type: "boolean", description: stagedOptionDescriptions[name] },
          ]),
        ),
        preserveUnused: {
          description: "Keep all unused managed hooks, or keep the listed hooks.",
          anyOf: [{ type: "boolean" }, { type: "array", items: { enum: VALID_HOOKS } }],
        },
      },
    },
    hooks: {
      type: "object",
      description: "Commands to run for each Git hook.",
      additionalProperties: false,
      properties: Object.fromEntries(VALID_HOOKS.map((name) => [name, commandList])),
    },
    staged: {
      type: "object",
      description:
        "Commands to run on staged files matching each glob. nano-hooks checks glob syntax when loading the configuration.",
      minProperties: 1,
      propertyNames: { minLength: 1 },
      additionalProperties: commandList,
    },
  },
  $defs: {
    commandList: {
      anyOf: [command, { type: "array", minItems: 1, items: command }],
    },
  },
};

const file = new URL("../schema.json", import.meta.url);
const generated = JSON.stringify(schema);
if (process.argv.includes("--check")) {
  if (JSON.stringify(JSON.parse(readFileSync(file, "utf8"))) !== generated) {
    throw new Error("schema.json is out of date. Run pnpm schema.");
  }
} else {
  writeFileSync(file, `${JSON.stringify(schema, null, 2)}\n`);
}
